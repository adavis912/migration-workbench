"""Write the GitHub Actions workflow for one Wave 1 app in the migration-pilots repository.

Same stage plan, gates and dry-run behaviour as the GitLab pipelines:
  real:      secret scan (Gitleaks), SAST (Semgrep), IaC scan (Checkov), terraform fmt/validate,
             terraform plan for staging and production with a read-only OIDC role
  dry run:   build, publish, apply (plans again, applies nothing), deploy, tests, cutover, roll-back
  human:     each cutover step (5% / 25% / 100%) waits for a required reviewer on its GitHub environment
Job names match the GitLab ones the workbench already knows, so the App Pipelines page reads both.

    python make_workflow.py CS-SURV2 cs-surv2 "p/default p/java p/owasp-top-ten" > .github/workflows/cs-surv2.yml
"""
import json, shlex, sys

TF = "1.9.8"


def q(s):
    """A YAML-safe double-quoted string."""
    return json.dumps(s)


def echo_job(name, needs, lines, extra=""):
    out = [f"  {name}:", f"    name: {name}", "    runs-on: ubuntu-latest", f"    needs: [{', '.join(needs)}]"]
    if extra:
        out.append(extra)
    out += ["    steps:", "      - name: Dry run", "        working-directory: .", "        run: |"]
    out += [f"          echo {shlex.quote(l)}" for l in lines]
    return "\n".join(out)


def tf_job(name, env, needs, apply=False):
    plan_title = f"terraform-plan {env}"
    lines = [
        f"  {name}:",
        f"    name: {name}",
        "    runs-on: ubuntu-latest",
        f"    needs: [{', '.join(needs)}]",
        "    steps:",
        "      - uses: actions/checkout@v4",
        "      - uses: hashicorp/setup-terraform@v3",
        "        with:",
        f"          terraform_version: {TF}",
        "          terraform_wrapper: false",
        "      - uses: aws-actions/configure-aws-credentials@v4",
        "        with:",
        "          role-to-assume: ${{ vars.AWS_PLAN_ROLE_ARN }}",
        "          aws-region: us-east-1",
        f"          role-session-name: gh-${{{{ github.run_id }}}}-{name}",
        "      - name: Discover the landing-zone values (read-only)",
        "        run: |",
        "          ACCT=$(aws sts get-caller-identity --query Account --output text)",
        "          VPC=$(aws ec2 describe-vpcs --filters Name=is-default,Values=true --query 'Vpcs[0].VpcId' --output text)",
        "          SUBNETS=$(aws ec2 describe-subnets --filters Name=vpc-id,Values=$VPC --query 'Subnets[:2].SubnetId' --output json | tr -d ' \\n')",
        "          {",
        "            echo \"ACCT=$ACCT\"",
        "            echo \"TF_VAR_vpc_id=$VPC\"",
        "            echo \"TF_VAR_private_subnet_ids=$SUBNETS\"",
        "            echo \"TF_VAR_kms_key_arn=arn:aws:kms:us-east-1:$ACCT:key/00000000-0000-0000-0000-000000000000\"",
        "            echo \"TF_VAR_acm_certificate_arn=arn:aws:acm:us-east-1:$ACCT:certificate/00000000-0000-0000-0000-000000000000\"",
        "          } >> \"$GITHUB_ENV\"",
        f"      - name: terraform init ({env} state)",
        "        run: >",
        "          terraform init -input=false",
        "          -backend-config=\"bucket=capstone-gh-tfstate-${ACCT}\"",
        f"          -backend-config=\"key=${{APP_ID}}/{env}/terraform.tfstate\"",
        "          -backend-config=\"region=us-east-1\" -backend-config=\"encrypt=true\"",
        f"      - name: terraform plan ({env})",
        "        env:",
        f"          TF_VAR_environment: {env}",
        "        run: |",
        f"          terraform plan -input=false -lock=false -no-color -out=tfplan-{env} | tee plan.txt",
        "          SUMMARY=$(grep -E '^(Plan:|No changes)' plan.txt | head -1)",
        f"          echo \"::notice title={plan_title}::$SUMMARY\"",
        f"          echo \"### {env}: $SUMMARY\" >> \"$GITHUB_STEP_SUMMARY\"",
    ]
    if apply:
        lines.append("          echo " + shlex.quote(f"DRY RUN - terraform apply skipped. The plan above is exactly what {name} would apply."))
    return "\n".join(lines)


def workflow(app_id, slug, semgrep_configs):
    d = f"apps/{slug}"
    cfg = " ".join(f"--config {c}" for c in semgrep_configs.split())
    parts = [f"""# Generated by github/make_workflow.py for {app_id}. DRY-RUN MODE: every stage runs; nothing is applied,
# deployed or routed. Terraform plans are real and use a read-only role through GitHub OIDC (no stored keys).
name: {app_id} migration pipeline
run-name: "{app_id} · ${{{{ github.event.head_commit.message || 'manual run' }}}}"

on:
  push:
    branches: [main]
    paths: ["{d}/**", ".github/workflows/{slug}.yml"]
  workflow_dispatch:

permissions:
  contents: read
  id-token: write

concurrency:
  group: {slug}
  cancel-in-progress: false

env:
  APP_ID: {app_id}
  AWS_DEFAULT_REGION: us-east-1
  TF_IN_AUTOMATION: "true"
  TF_VAR_app_id: {app_id}
  TF_VAR_wave: wave-1
  TF_VAR_data_classification: Internal
  TF_VAR_region: us-east-1
  TF_VAR_onprem_cidrs: '["10.200.0.0/16"]'
  TF_VAR_artifact_bucket_name: capstone-pilot-artifacts-placeholder
  TF_VAR_route53_zone_id: Z00000000PILOTPLACEHOLDER
  TF_VAR_app_dns_name: {slug}.pilot.example.internal
  TF_VAR_legacy_endpoint: legacy-{slug}.example.internal
  TF_VAR_alb_log_bucket_name: capstone-pilot-elb-logs-placeholder

defaults:
  run:
    working-directory: {d}

jobs:
  # ------------------------------------------------------------ Stage 1 · source gates (real)
  gitleaks:
    name: gitleaks
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Secret scan
        working-directory: .
        run: docker run --rm -v "$PWD/{d}:/src" zricethezav/gitleaks:v8.21.2 detect --source /src --no-git --redact --verbose --exit-code 1
  semgrep:
    name: semgrep
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Static analysis
        working-directory: .
        run: docker run --rm -v "$PWD/{d}:/src" -w /src semgrep/semgrep:1.99.0 semgrep scan {cfg} --error --metrics off .
  checkov:
    name: checkov
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Infrastructure-as-code scan
        working-directory: .
        run: docker run --rm -v "$PWD/{d}:/src" bridgecrew/checkov:3.2.500 -d /src --framework terraform --compact --quiet"""]
    parts.append("  # ------------------------------------------------------------ Stage 2-3 · build and publish (dry run)")
    parts.append(echo_job("build_java", ["gitleaks", "semgrep", "checkov"], [
        "DRY RUN [build] build_java - nothing is built, uploaded, deployed or routed.",
        "Commands this job would run:", "  mvn -B verify (unit tests + OWASP Dependency-Check)"]))
    parts.append(echo_job("trivy_scan_artifact", ["build_java"], [
        "DRY RUN [publish] trivy_scan_artifact - no artifact was built to scan.",
        "Command this job would run:", "  trivy fs --exit-code 1 --severity CRITICAL,HIGH target/"]))
    parts.append(echo_job("publish_artifact", ["build_java"], [
        "DRY RUN [publish] publish_artifact - nothing is uploaded.",
        "Command this job would run:", "  aws s3 cp $ARTIFACT s3://$ARTIFACT_BUCKET/$APP_ID/"]))
    parts.append("  # ------------------------------------------------------------ Stage 4 · Terraform (validate and plan are real)")
    parts.append(f"""  tf_validate:
    name: tf_validate
    runs-on: ubuntu-latest
    needs: [trivy_scan_artifact, publish_artifact]
    steps:
      - uses: actions/checkout@v4
      - uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: {TF}
          terraform_wrapper: false
      - run: terraform fmt -check -recursive -diff
      - run: terraform init -backend=false -input=false
      - run: terraform validate""")
    parts.append(tf_job("tf_plan_staging", "staging", ["tf_validate"]))
    parts.append(tf_job("tf_plan_production", "production", ["tf_validate"]))
    parts.append(tf_job("tf_apply_staging", "staging", ["tf_plan_staging", "tf_plan_production"], apply=True))
    parts.append(tf_job("tf_apply_production", "production", ["tf_plan_staging", "tf_plan_production"], apply=True))
    parts.append("  # ------------------------------------------------------------ Stage 4d-5 · deploy and test (dry run)")
    parts.append(echo_job("deploy_staging", ["tf_apply_staging", "tf_apply_production"], [
        "DRY RUN [deploy] deploy_staging - nothing is deployed.",
        "Command this job would run:", "  aws ssm send-command --document-name AWS-RunShellScript (rehydrate from the artifact)"]))
    parts.append(echo_job("deploy_production", ["deploy_staging"], [
        "DRY RUN [deploy] deploy_production - nothing is deployed.",
        "Command this job would run:", "  aws ssm send-command ... (production instances, 0% traffic until cutover)"]))
    parts.append(echo_job("integration_tests", ["deploy_production"], [
        "DRY RUN [test] integration_tests - would run against staging.", "  mvn -B verify -Pintegration"]))
    parts.append(echo_job("dast_zap", ["deploy_production"], [
        "DRY RUN [test] dast_zap - would scan staging.", "  zap-baseline.py -t https://$STAGING_URL -I"]))
    parts.append(echo_job("perf_k6", ["deploy_production"], [
        "DRY RUN [test] perf_k6 - would load-test staging.", "  k6 run perf/smoke.js"]))
    parts.append("  # ------------------------------------------------------------ Stage 6 · cutover: a person approves every step")
    prev = ["integration_tests", "dast_zap", "perf_k6"]
    for pct in (5, 25, 100):
        name = f"cutover_{pct}pct"
        parts.append(echo_job(name, prev, [
            f"DRY RUN [cutover] {name} - approved by a reviewer on the cutover-{pct}pct environment.",
            f"Would set the Route 53 weight to {pct}% AWS and watch the health alarm for 300 seconds.",
            "No DNS record is changed in dry-run mode."], extra=f"    environment: cutover-{pct}pct"))
        prev = [name]
    parts.append(echo_job("rollback_auto", ["cutover_5pct", "cutover_25pct", "cutover_100pct"], [
        "DRY RUN [cutover] rollback_auto - a cutover step failed; would set the AWS weight back to 0%."],
        extra="    if: ${{ failure() }}"))
    parts.append(echo_job("rollback_manual", ["cutover_5pct", "cutover_25pct", "cutover_100pct"], [
        "DRY RUN [cutover] rollback_manual - would send all traffic back to OCI."],
        extra="    if: ${{ failure() }}"))
    return "\n\n".join(parts) + "\n"


if __name__ == "__main__":
    sys.stdout.write(workflow(sys.argv[1], sys.argv[2], sys.argv[3]))
